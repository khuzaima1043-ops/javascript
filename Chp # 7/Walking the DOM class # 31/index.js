// DOM kya hai?

// DOM (Document Object Model) HTML document ka object-based representation/model hai jo browser create karta hai.

// JavaScript DOM ke through HTML document ko access aur interact kar sakti hai.

// Basic Structure
// document
//    ↓
// <html>
//    ├── <head>
//    │     └── <title>
//    │
//    └── <body>
//          ├── heading
//          ├── paragraph
//          └── button

// Important Properties

// document
// → Current HTML document ko represent karta hai.

// document.documentElement
// → Poora <html> element return karta hai.

// document.head
// → <head> element return karta hai.

// document.body
// → <body> element return karta hai.

// document.title
// → HTML ke <title> ki text value return karta hai.
// → Iska type normally string hota hai.

// Important Concept

// HTML = source code jo hum file mein likhte hain.
// DOM = browser ke andar us HTML ka object-based model/representation.

// JavaScript DOM ko use karke HTML document ko access aur baad mein manipulate kar sakti hai.

// Browser HTML Correction: 
// Agar HTML mein kuch invalid structure ho, browser usay parse karte waqt automatically correct/adjust kar sakta hai.

// One-line revision:

