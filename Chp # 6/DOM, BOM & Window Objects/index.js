// 🟢 2. BOM — Browser Object Model

// BOM = Browser Object Model

// Simple words:

// BOM JavaScript ko browser ke saath interact karne deta hai.

// Yani webpage ke HTML se nahi, browser environment se related cheezen.

// Examples:

// window
// browser history
// screen information
// browser/location related information

// Simple formula:

// BOM → Browser


// DOM = Document Object Model

// Yahan Document ka matlab tumhara webpage/HTML document hai.

// JavaScript browser ke HTML page ko objects ki form mein access kar sakti hai.

// Example HTML:

// <h1>Hello</h1>
// <p>Welcome</p>

// DOM ke through JavaScript in elements ko access/change kar sakti hai.

// Simple formula:

// DOM → Webpage/HTML


// 🟢 BOM vs DOM — sabse important

// Isko bas ye yaad rakho:

// BOM → Browser
// DOM → Webpage
// Example:

// Browser ki location/history/window se related kaam:

// ➡️ BOM

// HTML ke <h1>, <p>, <button> etc. ko access/change karna:

// ➡️ DOM


